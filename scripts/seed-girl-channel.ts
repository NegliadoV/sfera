async function seed() {
  console.log('🌱 Создаём seed-контент: канал "Дневник Ани"...\n');

  // 1. Проверяем/создаём пользователя Аня
  let [anya] = await db.select().from(user).where(eq(user.email, AUTHOR_EMAIL));
  if (!anya) {
    [anya] = await db.insert(user).values({
      name: 'Аня Лебедева',
      email: AUTHOR_EMAIL,
      image: 'https://images.unsplash.com/photo-1494790108377-be9c29b29330?w=200&q=80',
      userTag: 'anya_diary',
    }).returning();
    console.log(`✅ Создан пользователь: ${anya.name} (${anya.id})`);
  } else {
    console.log(`ℹ️  Пользователь уже существует: ${anya.name}`);
  }

  // 2. Проверяем/создаём вселенную
  let [universe] = await db.select().from(universes).where(eq(universes.slug, SLUG));
  if (!universe) {
    [universe] = await db.insert(universes).values({
      slug: SLUG,
      name: 'Дневник Ани 🌿',
      description: 'Честный лайфстайл-блог: книги, еда, путешествия, уход за собой и мысли вслух. Без фильтров.',
      icon: '🌿',
      sphereColor: '#ec4899',
      ownerId: anya.id,
      isPrivate: false,
    }).returning();
    console.log(`✅ Создана комната: "${universe.name}" (${universe.slug})`);
  } else {
    console.log(`ℹ️  Комната уже существует: ${universe.name}`);
  }

  // 3. Проверяем сколько постов уже есть
  const existing = await db.select({ id: content.id }).from(content).where(
    // @ts-ignore
    eq(content.universeId, universe.id)
  );
  if (existing.length >= posts.length) {
    console.log(`ℹ️  Посты уже созданы (${existing.length}). Пропускаем.`);
    process.exit(0);
  }

  // 4. Создаём посты
  const now = new Date();
  for (let i = 0; i < posts.length; i++) {
    const p = posts[i];
    const publishedAt = new Date(now.getTime() - (posts.length - i) * 2 * 24 * 60 * 60 * 1000);
    await db.insert(content).values({
      universeId: universe.id,
      authorId: anya.id,
      type: p.type,
      title: p.title,
      body: p.body,
      imageUrl: p.imageUrl,
      tags: p.tags,
      publishedAt,
      savesCount: Math.floor(Math.random() * 120) + 10,
    });
    console.log(`  📝 Пост ${i + 1}/${posts.length}: "${p.title}"`);
  }

  console.log('\n✅ Seed завершён!');
  console.log(`   Комната: /universes/${SLUG}/content`);
  process.exit(0);
}

seed().catch((e) => {
  console.error('❌ Ошибка:', e);
  process.exit(1);
});
