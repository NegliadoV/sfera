// Add landing section to each dictionary file
for (const [locale, translations] of Object.entries(landingTranslations)) {
  const filePath = path.join(DICT_DIR, `${locale}.ts`);
  let content = fs.readFileSync(filePath, 'utf-8');

  // Build the landing object string
  const lines = Object.entries(translations)
    .map(([key, val]) => `    ${key}: ${JSON.stringify(val)},`)
    .join('\n');
  const landingBlock = `  landing: {\n${lines}\n  },`;

  // Insert before closing `};`
  content = content.replace(/\n};\s*$/, `\n${landingBlock}\n};\n`);
  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`✅ ${locale}.ts updated`);
}

console.log('\nDone! All dictionaries updated with landing translations.');
