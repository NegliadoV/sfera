// Нормализация завуалированного мата (леетспик, транслит, символы маскировки)
export function normalizeObsceneText(text: string): string {
  if (!text) return '';
  // Обрабатываем слова по отдельности, сохраняя пробелы между ними
  return text
    .toLowerCase()
    // Замена похожих английских букв на русские
    .replace(/a/g, 'а')
    .replace(/b/g, 'б')
    .replace(/c/g, 'с')
    .replace(/e/g, 'е')
    .replace(/k/g, 'к')
    .replace(/m/g, 'м')
    .replace(/o/g, 'о')
    .replace(/p/g, 'р')
    .replace(/t/g, 'т')
    .replace(/x/g, 'х')
    .replace(/y/g, 'у')
    // Замена цифр и спецсимволов, используемых для обхода
    .replace(/0/g, 'о')
    .replace(/1/g, 'и')
    .replace(/3/g, 'з')
    .replace(/4/g, 'ч')
    .replace(/6/g, 'б')
    .replace(/@/g, 'а')
    .replace(/[$]/g, 'с')
    // Удаление маскировочных символов внутри слов (п*здец -> пздец, х.у.й -> хуй)
    .replace(/[\*\.\,\-\_\~\|\/\\\#\+\=]/g, '');
}

