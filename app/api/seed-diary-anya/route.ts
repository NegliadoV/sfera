export async function GET(req: Request) {
  const url = new URL(req.url);
  const secret = url.searchParams.get('secret');

  if (secret !== SEED_SECRET) {
    return NextResponse.json({ error: 'Forbidden' }, { status: 403 });
  }

  const log: string[] = [];

  try {
    // 1. User
    let [anya] = await db.select().from(user).where(eq(user.email, AUTHOR_EMAIL));
    if (!anya) {
      [anya] = await db.insert(user).values({
        name: 'Аня Лебедева',
        email: AUTHOR_EMAIL,
        image: 'https://images.unsplash.com/photo-1494790108377-be9c29b29330?w=200&q=80',
        userTag: 'anya_diary',
      }).returning();
      log.push(`✅ Создан пользователь: ${anya.name}`);
    } else {
      log.push(`ℹ️ Пользователь уже существует: ${anya.name}`);
    }

    // 2. Universe
    let [universe] = await db.select().from(universes).where(eq(universes.slug, SLUG));
    if (!universe) {
      [universe] = await db.insert(universes).values({
        slug: SLUG,
        name: 'Дневник Ани 🌿',
        description: 'Честный лайфстайл-блог: книги, еда, путешествия, уход за собой и мысли вслух. Без фильтров.',
        icon: '🌿',
        sphereColor: '#ec4899',
        ownerId: anya.id,
        isPrivate: false,
      }).returning();
      log.push(`✅ Создана комната: "${universe.name}"`);
    } else {
      log.push(`ℹ️ Комната уже существует: ${universe.name}`);
    }

    // 3. Posts
    const existing = await db.select({ id: content.id }).from(content)
      .where(eq(content.universeId, universe.id));

    if (existing.length >= posts.length) {
      log.push(`ℹ️ Посты уже созданы (${existing.length}). Пропускаем.`);
    } else {
      const now = new Date();
      for (let i = 0; i < posts.length; i++) {
        const p = posts[i];
        const publishedAt = new Date(now.getTime() - (posts.length - i) * 2 * 24 * 60 * 60 * 1000);
        await db.insert(content).values({
          universeId: universe.id,
          authorId: anya.id,
          type: p.type,
          title: p.title,
          body: p.body,
          imageUrl: p.imageUrl,
          tags: p.tags,
          publishedAt,
          savesCount: Math.floor(Math.random() * 120) + 10,
        });
        log.push(`📝 Пост ${i + 1}/${posts.length}: "${p.title}"`);
      }
    }

    return NextResponse.json({
      success: true,
      slug: SLUG,
      url: `/universes/${SLUG}/content`,
      log,
    });
  } catch (error: any) {
    return NextResponse.json({ error: error?.message ?? 'Unknown error', log }, { status: 500 });
  }
}
